const GROW_APFS: &str = "store=$(/usr/sbin/diskutil info / | /usr/bin/awk -F': *' '/APFS Physical Store/{print $2}') && /usr/sbin/diskutil apfs resizeContainer \"$store\" 0 >/dev/null";

/// A macOS Guest the SSH helpers reach: a container, or a machine
/// ([`MachineGuest`]). Its directory holds `login`, `known_hosts`, `setup`
/// and `grant` as described above.
pub trait Guest: Sync {
    fn name(&self) -> &str;
    /// The daemon VM it runs as.
    fn vm_id(&self) -> &str;
    fn dir(&self) -> Result<PathBuf>;
    fn mac_address(&self) -> Option<&str>;
    /// The virtiofs shares to mount once it is up: tag, host path, Guest path.
    fn mounts(&self) -> Vec<(String, PathBuf, String)>;
    /// Where commands run, and the `KEY=VALUE`s they get.
    fn workdir(&self) -> &str;
    fn env(&self) -> &[String];
}

impl Guest for Container {
    fn name(&self) -> &str {
        &self.name
    }
    fn vm_id(&self) -> &str {
        &self.vm_id
    }
    fn dir(&self) -> Result<PathBuf> {
        container::container_dir(&self.id)
    }
    fn mac_address(&self) -> Option<&str> {
        self.mac_address.as_deref()
    }
    fn mounts(&self) -> Vec<(String, PathBuf, String)> {
        self.volumes
            .iter()
            .enumerate()
            .map(|(i, v)| (format!("v{i}"), v.host.clone(), v.target.clone()))
            .collect()
    }
    fn workdir(&self) -> &str {
        &self.workdir
    }
    fn env(&self) -> &[String] {
        &self.env
    }
}

fn is_active(guest: &dyn Guest) -> bool {
    container::active(&container::vm_state_of(guest.vm_id()))
}

pub(crate) fn clone_file(source: &Path, target: &Path) -> Result<()> {
    let s = CString::new(source.as_os_str().as_encoded_bytes())?;
    let t = CString::new(target.as_os_str().as_encoded_bytes())?;
    if unsafe { libc::clonefile(s.as_ptr(), t.as_ptr(), 0) } != 0 {
        return Err(std::io::Error::last_os_error())
            .with_context(|| format!("APFS clone of {} failed", source.display()));
    }
    // Image files are read-only; the clone is this container's writable copy.
    fs::set_permissions(target, fs::Permissions::from_mode(0o600))?;
    Ok(())
}

/// Random locally administered unicast MAC.
pub(crate) fn random_mac() -> String {
    let hex = random_hex(6);
    let first = u8::from_str_radix(&hex[..2], 16).unwrap() & 0xfc | 0x02;
    let rest: Vec<&str> = (1..6).map(|i| &hex[2 * i..2 * i + 2]).collect();
    format!("{first:02x}:{}", rest.join(":"))
}

fn normalize_mac(mac: &str) -> Option<String> {
    let octets: Vec<u8> = mac
        .split(':')
        .map(|o| u8::from_str_radix(o, 16).ok())
        .collect::<Option<_>>()?;
    (octets.len() == 6).then(|| {
        octets
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect::<Vec<_>>()
            .join(":")
    })
}

/// Newest lease for `mac` in a vmnet `dhcpd_leases` file. Its hardware
/// addresses drop leading zeros ("1,a:2:..."), so both sides are normalized.
pub fn lease_ip(leases: &str, mac: &str) -> Option<String> {
    let wanted = normalize_mac(mac)?;
    let mut best: Option<(u64, String)> = None;
    for block in leases.split('}') {
        let mut ip = None;
        let mut hw = None;
        let mut lease = 0;
        for line in block.lines() {
            match line.trim().split_once('=') {
                Some(("ip_address", v)) => ip = Some(v.to_owned()),
                Some(("hw_address", v)) => {
                    hw = v.split_once(',').and_then(|(_, m)| normalize_mac(m))
                }
                Some(("lease", v)) => {
                    lease = u64::from_str_radix(v.trim_start_matches("0x"), 16).unwrap_or(0)
                }
                _ => {}
            }
        }
        if let (Some(ip), Some(hw)) = (ip, hw) {
            if hw == wanted && best.as_ref().is_none_or(|(l, _)| lease >= *l) {
                best = Some((lease, ip));
            }
        }
    }
    best.map(|(_, ip)| ip)
}

pub fn guest_ip(guest: &dyn Guest, timeout: Duration) -> Result<String> {
    let mac = guest.mac_address().context("guest has no MAC address")?;
    let deadline = Instant::now() + timeout;
    loop {
        if let Some(ip) = fs::read_to_string(LEASES)
            .ok()
            .and_then(|l| lease_ip(&l, mac))
        {
            return Ok(ip);
        }
        if !is_active(guest) {
            bail!("{} is not running", guest.name())
        }
        if Instant::now() > deadline {
            bail!("timed out waiting for the macOS Guest's DHCP lease")
        }
        std::thread::sleep(Duration::from_secs(1));
    }
}

pub fn key() -> Result<PathBuf> {
    let dir = home::private_dir(&home::root()?.join("ssh"))?;
    let key = dir.join("id_ed25519");
    if !key.exists() {
        let status = Command::new("/usr/bin/ssh-keygen")
            .args(["-q", "-t", "ed25519", "-N", "", "-C", "veynodevm", "-f"])
            .arg(&key)
            .stdin(Stdio::null())
            .status()?;
        if !status.success() {
            bail!("ssh-keygen failed")
        }
    }
    Ok(key)
}

pub(crate) fn login(guest: &dyn Guest) -> Result<(String, String)> {
    let text = fs::read_to_string(guest.dir()?.join("login"))?;
    let (user, password) = text.split_once('\n').context("invalid login file")?;
    Ok((user.to_owned(), password.trim_end_matches('\n').to_owned()))
}

/// `ssh`/`scp` with this guest's known_hosts and the home key.
fn ssh_base(program: &str, guest: &dyn Guest) -> Result<Command> {
    let dir = guest.dir()?;
    let mut command = Command::new(program);
    command
        .arg("-i")
        .arg(key()?)
        .args([
            "-o",
            "IdentitiesOnly=yes",
            "-o",
            "StrictHostKeyChecking=accept-new",
        ])
        .arg("-o")
        // Quoted: an unquoted path splits at the space in "Application Support".
        .arg(format!(
            "UserKnownHostsFile={}",
            crate::windows_guest::config_path(&dir.join("known_hosts"))
        ))
        .args([
            "-o",
            "ConnectTimeout=10",
            "-o",
            "LogLevel=ERROR",
            "-o",
            "ServerAliveInterval=15",
        ]);
    Ok(command)
}

fn quote(word: &str) -> String {
    if !word.is_empty()
        && word
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"-_./=:@%+,".contains(&b))
    {
        word.to_owned()
    } else {
        format!("'{}'", word.replace('\'', "'\\''"))
    }
}

fn wait_for_ssh(guest: &dyn Guest, ip: &str, deadline: Instant) -> Result<()> {
    let address: SocketAddr = format!("{ip}:22").parse()?;
    loop {
        if TcpStream::connect_timeout(&address, Duration::from_secs(2)).is_ok() {
            return Ok(());
        }
        if !is_active(guest) {
            bail!("{} stopped while booting", guest.name())
        }
        if Instant::now() > deadline {
            bail!("timed out waiting for SSH on {ip} (is Remote Login enabled in the image?)")
        }
        std::thread::sleep(Duration::from_secs(1));
    }
}

/// Whether the home key logs in. Only an explicit authentication refusal is
/// "no"; other failures (sshd still starting) are retried, then reported.
fn key_works(guest: &dyn Guest, user: &str, ip: &str) -> Result<bool> {
    let mut last = String::new();
    for attempt in 0..5 {
        if attempt > 0 {
            std::thread::sleep(Duration::from_secs(2));
        }
        let output = ssh_base("/usr/bin/ssh", guest)?
            .args(["-o", "BatchMode=yes", "-o", "PasswordAuthentication=no"])
            .arg(format!("{user}@{ip}"))
            .arg("true")
            .stdin(Stdio::null())
            .output()?;
        if output.status.success() {
            return Ok(true);
        }
        last = String::from_utf8_lossy(&output.stderr).trim().to_owned();
        if last.contains("Permission denied") {
            return Ok(false);
        }
    }
    bail!("SSH to {user}@{ip} failed: {last}")
}

/// Authorize the home key with the image login (password through SSH_ASKPASS).
fn install_key(guest: &dyn Guest, user: &str, ip: &str) -> Result<()> {
    let dir = guest.dir()?;
    let askpass = dir.join("askpass");
    if !askpass.exists() {
        let mut file = fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .mode(0o700)
            .open(&askpass)?;
        file.write_all(b"#!/bin/sh\nexec /usr/bin/sed -n 2p \"$(dirname \"$0\")/login\"\n")?;
    }
    let public = fs::read(key()?.with_extension("pub"))?;
    let mut child = ssh_base("/usr/bin/ssh", guest)?
        .args([
            "-o",
            "PubkeyAuthentication=no",
            "-o",
            "PreferredAuthentications=password,keyboard-interactive",
            "-o",
            "NumberOfPasswordPrompts=1",
        ])
        .env("SSH_ASKPASS", &askpass)
        .env("SSH_ASKPASS_REQUIRE", "force")
        .env("DISPLAY", ":0")
        .arg(format!("{user}@{ip}"))
        .arg("umask 077; mkdir -p ~/.ssh && cat >> ~/.ssh/authorized_keys")
        .stdin(Stdio::piped())
        .stdout(Stdio::null())
        .stderr(Stdio::piped())
        .spawn()?;
    child.stdin.take().unwrap().write_all(&public)?;
    let output = child.wait_with_output()?;
    if !output.status.success() {
        bail!(
            "cannot log in to the macOS Guest as {user}: {} (set VEYNODEVM_MACOS_PASSWORD for images without the Tart default login)",
            String::from_utf8_lossy(&output.stderr).trim()
        )
    }
    Ok(())
}

/// Run a shell command in the Guest, returning (status, stdout, stderr).
pub(crate) fn remote(
    guest: &dyn Guest,
    ip: &str,
    script: &str,
    stdin: Option<&[u8]>,
) -> Result<(i32, Vec<u8>, Vec<u8>)> {
    let (user, _) = login(guest)?;
    let mut child = ssh_base("/usr/bin/ssh", guest)?
        .args(["-o", "BatchMode=yes"])
        .arg(format!("{user}@{ip}"))
        .arg(script)
        .stdin(if stdin.is_some() {
            Stdio::piped()
        } else {
            Stdio::null()
        })
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()?;
    if let Some(bytes) = stdin {
        child.stdin.take().unwrap().write_all(bytes)?;
    }
    let output = child.wait_with_output()?;
    Ok((
        output.status.code().unwrap_or(255),
        output.stdout,
        output.stderr,
    ))
}

/// Replaces this process with an SSH session running `script` in the Guest
/// on this process's stdio; returns only when that cannot start.
pub(crate) fn exec_remote(guest: &dyn Guest, ip: &str, script: &str) -> Result<()> {
    use std::os::unix::process::CommandExt;
    let (user, _) = login(guest)?;
    let error = ssh_base("/usr/bin/ssh", guest)?
        .args(["-o", "BatchMode=yes", "-T"])
        .arg(format!("{user}@{ip}"))
        .arg(script)
        .exec();
    Err(error.into())
}

/// `sudo` with the login password on stdin (Tart images also allow NOPASSWD).
fn sudo(guest: &dyn Guest, ip: &str, script: &str) -> Result<()> {
    let (_, password) = login(guest)?;
    let (code, _, stderr) = remote(
        guest,
        ip,
        &format!("sudo -S -p '' /bin/sh -c {}", quote(script)),
        Some(format!("{password}\n").as_bytes()),
    )?;
    if code != 0 {
        bail!("{script}: {}", String::from_utf8_lossy(&stderr).trim())
    }
    Ok(())
}

/// Wait for the Guest, authorize the key and mount volumes. Returns its IP.
pub fn ensure_ready(guest: &dyn Guest, quiet: bool) -> Result<String> {
    let deadline = Instant::now() + BOOT_TIMEOUT;
    let say = |m: &str| {
        if !quiet {
            super::progress(m)
        }
    };
    let ip = guest_ip(guest, BOOT_TIMEOUT)?;
    wait_for_ssh(guest, &ip, deadline)?;
    let (user, _) = login(guest)?;
    if !key_works(guest, &user, &ip)? {
        say(&format!("authorizing SSH key for {user}@{ip}"));
        install_key(guest, &user, &ip)?;
        if !key_works(guest, &user, &ip)? {
            bail!("SSH key was installed but is not accepted by the Guest")
        }
    }
    let setup = guest.dir()?.join("setup");
    if let Ok(script) = fs::read_to_string(&setup) {
        say("applying first-boot settings");
        sudo(guest, &ip, &script)?;
        fs::remove_file(&setup)?;
    }
    // Renaming claims the one-time grant, so concurrent callers skip it.
    let dir = guest.dir()?;
    if fs::rename(dir.join("grant"), dir.join("grant.running")).is_ok() {
        say("granting SSH sessions Accessibility and Automation");
        super::macos_grant::grant(guest, &ip);
        fs::remove_file(dir.join("grant.running"))?;
    }
    for (tag, host, target) in guest.mounts() {
        let quoted = quote(&target);
        let (code, out, _) = remote(
            guest,
            &ip,
            &format!(
                // macOS reports the type as AppleVirtIOFS; any mount on the
                // target means the tag is already in use.
                "/sbin/mount | grep -qF {}",
                quote(&format!(" on {target} ("))
            ),
            None,
        )?;
        if code == 0 && out.is_empty() {
            continue;
        }
        say(&format!("mounting {} at {target}", host.display()));
        sudo(
            guest,
            &ip,
            &format!("mkdir -p {quoted} && /sbin/mount_virtiofs {tag} {quoted}"),
        )?;
    }
    Ok(ip)
}

fn remote_command(guest: &dyn Guest, argv: &[String]) -> String {
    let mut script = String::new();
    if !guest.workdir().is_empty() {
        script.push_str(&format!("cd {} && ", quote(guest.workdir())));
    }
    if !guest.env().is_empty() {
        script.push_str("env ");
        for e in guest.env() {
            script.push_str(&quote(e));
            script.push(' ');
        }
    }
    script.push_str(&argv.iter().map(|a| quote(a)).collect::<Vec<_>>().join(" "));
    script
}

/// Run `argv` (a login shell when empty) with stdout/stderr inherited and
/// stdin only with `-i`/`-t`; returns the remote exit status.
pub fn exec(guest: &dyn Guest, argv: &[String], tty: bool, interactive: bool) -> Result<i32> {
    let mut command = exec_command(guest, argv, tty)?;
    if !(tty || interactive) {
        command.stdin(Stdio::null());
    }
    Ok(command.status()?.code().unwrap_or(255))
}

/// `ssh` running `argv` (a login shell when empty), `-tt` with `tty`.
pub fn exec_command(guest: &dyn Guest, argv: &[String], tty: bool) -> Result<Command> {
    let ip = ensure_ready(guest, false)?;
    let (user, _) = login(guest)?;
    let mut command = ssh_base("/usr/bin/ssh", guest)?;
    command.args(["-o", "BatchMode=yes"]);
    if tty {
        command.arg("-tt");
    }
    let shell = ["/bin/zsh".to_owned(), "-l".to_owned()];
    let argv = if argv.is_empty() { &shell[..] } else { argv };
    command
        .arg(format!("{user}@{ip}"))
        .arg(remote_command(guest, argv));
    Ok(command)
}

/// `ssh -tt` running `argv` (a login shell when empty), for callers that give
/// it a terminal of their own (the web UI terminal, `session`).
pub fn shell_command(guest: &dyn Guest, argv: &[String]) -> Result<Command> {
    let ip = ensure_ready(guest, true)?;
    let (user, _) = login(guest)?;
    let mut command = ssh_base("/usr/bin/ssh", guest)?;
    command.args(["-o", "BatchMode=yes", "-tt"]);
    let shell = ["/bin/zsh".to_owned(), "-l".to_owned()];
    let argv = if argv.is_empty() { &shell[..] } else { argv };
    command
        .arg(format!("{user}@{ip}"))
        .arg(remote_command(guest, argv));
    Ok(command)
}

/// The browser desktop's clipboard: `macos_clipboard.js` in the Guest's login
/// session (where the pasteboard lives), JSON lines on stdin and stdout.
pub fn clipboard_command(guest: &dyn Guest) -> Result<Command> {
    let ip = ensure_ready(guest, true)?;
    let (user, _) = login(guest)?;
    let mut command = ssh_base("/usr/bin/ssh", guest)?;
    command
        .args(["-o", "BatchMode=yes"])
        .arg(format!("{user}@{ip}"))
        .arg(clipboard_script());
    Ok(command)
}

fn clipboard_script() -> String {
    format!(
        "uid=$(id -u); exec sudo -n launchctl asuser \"$uid\" sudo -n -u \"#$uid\" /usr/bin/osascript -l JavaScript -e {}",
        quote(include_str!("macos_clipboard.js"))
    )
}

/// Start the guest's COMMAND in the background; its output is appended
/// to `~/.veynodevm/main.log` and its status written to `~/.veynodevm/exit`.
pub fn start_command(container: &Container) -> Result<()> {
    let ip = ensure_ready(container, true)?;
    let inner = format!(
        "{}; echo $? > \"$HOME/{EXIT}\"",
        remote_command(container, &container.argv)
    );
    let (code, _, stderr) = remote(
        container,
        &ip,
        &format!(
            "mkdir -p .veynodevm && rm -f {EXIT} && nohup /bin/sh -c {} >> {LOG} 2>&1 < /dev/null &",
            quote(&inner)
        ),
        None,
    )?;
    if code != 0 {
        bail!(
            "starting the command failed: {}",
            String::from_utf8_lossy(&stderr).trim()
        )
    }
    Ok(())
}

/// Print the background command's output; with `follow`, until it exits.
pub fn logs(container: &Container, follow: bool) -> Result<i32> {
    let status = logs_command(container, follow)?
        .stdin(Stdio::null())
        .status()?;
    Ok(status.code().unwrap_or(255))
}

/// `ssh` printing the background command's output (see [`logs`]).
pub fn logs_command(container: &Container, follow: bool) -> Result<Command> {
    if container.argv.is_empty() {
        bail!(
            "{} was started without a COMMAND, so it has no output to show; use veynodevm exec",
            container.name
        )
    }
    let ip = ensure_ready(container, true)?;
    let (user, _) = login(container)?;
    let script = if follow {
        format!("touch {LOG}; tail -n +1 -f {LOG} & t=$!; while [ ! -e {EXIT} ]; do sleep 1; done; sleep 1; kill $t")
    } else {
        format!("cat {LOG} 2>/dev/null; true")
    };
    let mut command = ssh_base("/usr/bin/ssh", container)?;
    command
        .args(["-o", "BatchMode=yes"])
        .arg(format!("{user}@{ip}"))
        .arg(script);
    Ok(command)
}

/// Wait until the worker reports the VM running; a VM that fails to start
/// (for example over Apple's two-macOS-VM limit) is an error, not "Up".
pub fn wait_started(container: &Container) -> Result<()> {
    let deadline = Instant::now() + Duration::from_secs(60);
    loop {
        let status = daemon_call("status", json!({"id":container.vm_id}))?;
        let state = status["state"].as_str().unwrap_or_default();
        if state == "running" && status["runtime"]["state"] == "running" {
            return Ok(());
        }
        if matches!(state, "crashed" | "stopped" | "error") {
            let message = status["runtime"]["message"]
                .as_str()
                .unwrap_or("the worker exited");
            if message.contains("exceeds the limit") {
                bail!("Apple allows at most two macOS VMs running at once on a host; stop one and try again ({message})")
            }
            bail!("the macOS VM failed to start: {message}")
        }
        if Instant::now() > deadline {
            bail!("timed out waiting for the macOS VM to start")
        }
        std::thread::sleep(Duration::from_millis(250));
    }
}

/// Bounded capture for `--json` and MCP-style callers.
pub fn exec_capture(container: &Container, argv: &[String]) -> Result<Value> {
    let ip = ensure_ready(container, true)?;
    let (code, stdout, stderr) = remote(container, &ip, &remote_command(container, argv), None)?;
    Ok(
        json!({"exit_code":code,"stdout":String::from_utf8_lossy(&stdout),"stderr":String::from_utf8_lossy(&stderr),"timed_out":false}),
    )
}

/// `scp` of `host` into (`inward`) or out of the Guest's `guest` path.
pub fn cp_command(
    container: &Container,
    inward: bool,
    host: &Path,
    guest: &str,
) -> Result<Command> {
    if container.os != "darwin" {
        bail!("cp is implemented for macOS containers")
    }
    scp_command(container, inward, host, guest)
}

/// `scp -r` of `host` into (`inward`) or out of the Guest's `path`.
fn scp_command(guest: &dyn Guest, inward: bool, host: &Path, path: &str) -> Result<Command> {
    let ip = ensure_ready(guest, true)?;
    let (user, _) = login(guest)?;
    let remote = format!("{user}@{ip}:{path}");
    let mut command = ssh_base("/usr/bin/scp", guest)?;
    command.args(["-o", "BatchMode=yes", "-r", "-q"]);
    if inward {
        command.arg(host).arg(remote);
    } else {
        command.arg(remote).arg(host);
    }
    Ok(command)
}

/// Shut the Guest down over SSH, then the power button, then a hard stop.
pub fn stop(container: &Container, timeout: Duration) -> Result<()> {
    if let Ok(ip) = guest_ip(container, Duration::ZERO) {
        if key_works(container, &login(container)?.0, &ip).unwrap_or(false) {
            let _ = sudo(container, &ip, "/sbin/shutdown -h now");
            if container::wait_stopped(container, timeout.max(Duration::from_secs(30))) {
                return Ok(());
            }
        }
    }
    let _ = daemon_call("shutdown", json!({"id":container.vm_id}));
    if container::wait_stopped(container, timeout) {
        return Ok(());
    }
    daemon_call(
        "force_stop",
        json!({"id":container.vm_id,"confirm":container.vm_id}),
    )?;
    if !container::wait_stopped(container, Duration::from_secs(15)) {
        bail!("container {} did not stop", container.name)
    }
    Ok(())
}

pub fn create_and_start(
    options: &RunOptions,
    store: &Store,
    image: &ImageRecord,
) -> Result<Container> {
    let machine = store.macos_dir(image)?;
    let vm_config: Value = serde_json::from_slice(&fs::read(machine.join("vm.json"))?)?;
    match options.gpus.as_deref() {
        None | Some("all" | "metal") => {}
        Some(other) => bail!("macOS containers always get Apple's paravirtualized Metal GPU; --gpus {other} is for Linux images"),
    }
    if options.entrypoint.is_some() {
        bail!("macOS containers have no entrypoint; pass the COMMAND after the image")
    }
    let runtime = home::Runtime::load()?;
    let id = random_hex(6);
    let name = container::container_name(options, image, &id)?;
    let setup = first_boot_script(options, &runtime, &name)?;
    let ports = container::parse_ports(options, false)?;
    let volumes = container::parse_volumes(options)?;
    let min_cpus = vm_config["cpuCountMin"].as_u64().unwrap_or(2) as u32;
    let min_memory = vm_config["memorySizeMin"].as_u64().unwrap_or(4 << 30) >> 20;
    let cpus = options
        .cpus
        .unwrap_or(vm_config["cpuCount"].as_u64().unwrap_or(4) as u32);
    let memory_mib = options
        .memory_mib
        .unwrap_or(vm_config["memorySize"].as_u64().unwrap_or(8 << 30) >> 20);
    if cpus < min_cpus || memory_mib < min_memory {
        bail!("this image needs at least {min_cpus} CPUs and {min_memory} MiB of memory")
    }
    let user = options
        .user
        .clone()
        .unwrap_or_else(|| DEFAULT_LOGIN.0.to_owned());
    let password = image_password();
    let dir = container::container_dir(&id)?;
    fs::create_dir(&dir)?;
    fs::set_permissions(&dir, fs::Permissions::from_mode(0o700))?;
    let result = (|| -> Result<Container> {
        let identity = home::private_dir(&dir.join("machine"))?;
        clone_file(&machine.join("disk.img"), &dir.join("disk.img"))?;
        if let Some(gib) = options.disk_gib {
            super::gpt::grow(&dir.join("disk.img"), gib << 30)?;
        }
        if !setup.is_empty() {
            fs::write(dir.join("setup"), &setup)?;
        }
        fs::write(dir.join("grant"), "")?;
        copy_identity(&machine, "nvram.bin", &identity)?;
        write_login(&dir, &user, &password)?;
        let mac = random_mac();
        let vm_id = format!("c-{id}");
        let vm = json!({
            "backend": "apple-virtualization",
            "id": vm_id,
            "guest": "macos",
            "cpus": cpus,
            "memory_mib": memory_mib,
            "disk": dir.join("disk.img"),
            "machine_identity_dir": identity,
            "mac_address": mac,
            "screen_sharing_login": dir.join("login"),
            "width": 1920,
            "height": 1080,
            "window": options.desktop,
            // A sound card the host discards; the Guest service records it for the viewer.
            "audio": true,
            "shares": volumes.iter().enumerate().map(|(i, v)| json!({"tag":format!("v{i}"),"path":v.host,"read_only":v.read_only})).collect::<Vec<_>>(),
        });
        let container = Container {
            id: id.clone(),
            name,
            image: image.reference.clone(),
            config_digest: image.config_digest.clone(),
            argv: options.command.clone(),
            env: options
                .env
                .iter()
                .filter(|e| e.contains('='))
                .cloned()
                .collect(),
            workdir: options.workdir.clone().unwrap_or_default(),
            user,
            ports,
            volumes,
            backend: "apple-virtualization".into(),
            gpus: Some("metal".into()),
            desktop: options.desktop,
            engine: false,
            auto_remove: options.auto_remove,
            cpus,
            memory_mib,
            created_at: container::now(),
            vm_id: vm_id.clone(),
            os: "darwin".into(),
            mac_address: Some(mac),
            session_port: None,
            fork_of: None,
            icon: None,
            desktop_size: None,
            init: None,
            tty: false,
            stdin: false,
        };
        container::save(&container)?;
        daemon_call("create", vm)?;
        if let Err(e) =
            daemon_call("start", json!({"id":vm_id})).and_then(|_| wait_started(&container))
        {
            let _ = daemon_call("force_stop", json!({"id":vm_id,"confirm":vm_id}));
            let _ = daemon_call("delete", json!({"id":vm_id,"confirm":vm_id}));
            return Err(e);
        }
        if !container.ports.is_empty() {
            super::proxy::spawn(&container)?;
        }
        Ok(container)
    })();
    if result.is_err() {
        let _ = fs::remove_dir_all(&dir);
    }
    result
}

/// The worker's identity files in `identity` from those in `from`, whose
/// NVRAM is `nvram` (`nvram.bin` in an image, `auxiliary-storage.bin` in a
/// machine): the NVRAM is an APFS clone, the rest copies.
fn copy_identity(from: &Path, nvram: &str, identity: &Path) -> Result<()> {
    clone_file(&from.join(nvram), &identity.join("auxiliary-storage.bin"))?;
    for file in ["hardware-model.bin", "machine-id.bin"] {
        if from.join(file).exists() {
            fs::copy(from.join(file), identity.join(file))?;
            fs::set_permissions(identity.join(file), fs::Permissions::from_mode(0o600))?;
        }
    }
    Ok(())
}

/// `<dir>/login`, "user\npassword" (0600).
fn write_login(dir: &Path, user: &str, password: &str) -> Result<()> {
    let mut file = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(dir.join("login"))?;
    file.write_all(format!("{user}\n{password}\n").as_bytes())?;
    Ok(())
}

/// The image's login password: `VEYNODEVM_MACOS_PASSWORD`, else Tart's default.
fn image_password() -> String {
    std::env::var("VEYNODEVM_MACOS_PASSWORD").unwrap_or_else(|_| DEFAULT_LOGIN.1.to_owned())
}

/// Root commands for the first boot: name the Guest after the container
/// (clones share the image's identity and hostname), grow APFS into a larger
/// disk, then DNS and MTU (container flags, else the runtime.json defaults).
fn first_boot_script(options: &RunOptions, runtime: &home::Runtime, name: &str) -> Result<String> {
    first_boot(
        name,
        options.disk_gib.is_some(),
        &options.dns,
        options.mtu,
        runtime,
    )
}

fn first_boot(
    name: &str,
    grown: bool,
    dns: &[String],
    mtu: Option<u16>,
    runtime: &home::Runtime,
) -> Result<String> {
    let host: String = name
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '-' })
        .collect::<String>()
        .trim_matches('-')
        .chars()
        .take(63)
        .collect();
    let host = if host.is_empty() {
        "veynodevm".to_owned()
    } else {
        host
    };
    let mut lines = vec![format!(
        "for key in ComputerName LocalHostName HostName; do /usr/sbin/scutil --set $key {host}; done"
    )];
    if grown {
        lines.push(GROW_APFS.to_owned());
    }
    let dns: Vec<String> = if dns.is_empty() {
        runtime.dns.iter().map(ToString::to_string).collect()
    } else {
        dns.iter()
            .map(|d| {
                d.parse::<std::net::IpAddr>()
                    .map(|ip| ip.to_string())
                    .with_context(|| format!("invalid --dns {d}"))
            })
            .collect::<Result<_>>()?
    };
    if !dns.is_empty() {
        lines.push(format!("/usr/sbin/networksetup -listallnetworkservices | /usr/bin/tail -n +2 | while IFS= read -r s; do /usr/sbin/networksetup -setdnsservers \"${{s#\\*}}\" {}; done", dns.join(" ")));
    }
    if let Some(mtu) = mtu.or(runtime.mtu) {
        if !(1280..=9000).contains(&mtu) {
            bail!("--mtu must be between 1280 and 9000 for macOS containers")
        }
        lines.push(format!("for d in $(/usr/sbin/networksetup -listallhardwareports | /usr/bin/awk '/^Device:/{{print $2}}'); do /usr/sbin/networksetup -setMTU \"$d\" {mtu}; done"));
    }
    Ok(std::iter::once("set -e")
        .chain(lines.iter().map(String::as_str))
        .map(|l| format!("{l}\n"))
        .collect())
}

