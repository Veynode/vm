/// Where a macOS machine's shares mount, as `machine.inspect` gives them.
pub const SHARED: &str = "/Volumes/My Shared Files";

/// A macOS machine as the SSH helpers see it: its directory is
/// `<home>/machines/NAME`, laid out like a container's (`disk.img`,
/// `machine/`, `login`, `known_hosts`, `setup`, `grant`), and its VM id is
/// its name.
pub struct MachineGuest {
    name: String,
    dir: PathBuf,
    mac: Option<String>,
    shares: Vec<(String, PathBuf)>,
    workdir: String,
    env: Vec<String>,
}

impl MachineGuest {
    /// `machine` with its daemon VM configuration (`status` → `config`).
    pub fn new(machine: &Machine, config: &Value) -> Result<Self> {
        let shares = config["shares"]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(|s| Some((s["tag"].as_str()?.to_owned(), s["path"].as_str()?.into())))
            .collect();
        Ok(Self {
            name: machine.name.clone(),
            dir: machines::dir(&machine.name)?,
            mac: config["mac_address"].as_str().map(str::to_owned),
            shares,
            workdir: String::new(),
            env: Vec::new(),
        })
    }
}

impl Guest for MachineGuest {
    fn name(&self) -> &str {
        &self.name
    }
    fn vm_id(&self) -> &str {
        &self.name
    }
    fn dir(&self) -> Result<PathBuf> {
        Ok(self.dir.clone())
    }
    fn mac_address(&self) -> Option<&str> {
        self.mac.as_deref()
    }
    fn mounts(&self) -> Vec<(String, PathBuf, String)> {
        self.shares
            .iter()
            .map(|(tag, host)| (tag.clone(), host.clone(), format!("{SHARED}/{tag}")))
            .collect()
    }
    fn workdir(&self) -> &str {
        &self.workdir
    }
    fn env(&self) -> &[String] {
        &self.env
    }
}

fn invalid(message: impl Into<String>) -> anyhow::Error {
    refuse(ErrorCode::Invalid, message)
}

/// What `machine.create {from}` takes beyond the image (`docs/api.md`).
struct MachineSpec {
    name: String,
    from: String,
    user: String,
    cpus: Option<u64>,
    memory_mib: Option<u64>,
    disk_gib: Option<u64>,
    shares: Vec<(String, PathBuf, bool)>,
    /// `(host, guest)`, served by the daemon's publisher while it runs.
    ports: Vec<(u16, u16)>,
}

fn machine_spec(args: &Value) -> Result<MachineSpec> {
    let text = |field: &str| -> Result<Option<String>> {
        match &args[field] {
            Value::Null => Ok(None),
            Value::String(s) if !s.is_empty() => Ok(Some(s.clone())),
            _ => Err(invalid(format!("{field} must be a non-empty string"))),
        }
    };
    let number = |field: &str, range: std::ops::RangeInclusive<u64>| -> Result<Option<u64>> {
        match &args[field] {
            Value::Null => Ok(None),
            value => value
                .as_u64()
                .filter(|n| range.contains(n))
                .map(Some)
                .ok_or_else(|| {
                    invalid(format!(
                        "{field} must be {} through {}",
                        range.start(),
                        range.end()
                    ))
                }),
        }
    };
    let name = text("name")?.ok_or_else(|| invalid("name is required"))?;
    crate::validate_id(&name).map_err(|e| invalid(e.to_string()))?;
    match text("os")?.as_deref() {
        None | Some("macos") => {}
        Some(other) => {
            return Err(invalid(format!(
                "from is a macOS image; os {other} takes disk or iso"
            )))
        }
    }
    let from = text("from")?.ok_or_else(|| invalid("a macOS machine needs from: its image"))?;
    for field in [
        "disk",
        "iso",
        "driversIso",
        "unattended",
        "attach",
        "diskBus",
        "monitor",
    ] {
        if !args[field].is_null() {
            return Err(invalid(format!(
                "{field} is not an option of macOS machines"
            )));
        }
    }
    match text("gpu")?.as_deref() {
        None | Some("none" | "all" | "metal") => {}
        Some(other) => {
            return Err(invalid(format!(
                "macOS machines get Apple's paravirtualized Metal GPU; gpu {other} is for Linux or Windows"
            )))
        }
    }
    match text("backend")?.as_deref() {
        None | Some("apple" | "apple-virtualization") => {}
        Some(_) => return Err(invalid("macOS machines run on Apple Virtualization")),
    }
    let shares = match &args["shares"] {
        Value::Null => Vec::new(),
        Value::Array(shares) => shares
            .iter()
            .map(|s| {
                let host = s["hostPath"].as_str().unwrap_or_default();
                let path = fs::canonicalize(host)
                    .map_err(|_| invalid(format!("share not found: {host}")))?;
                let tag = s["tag"]
                    .as_str()
                    .filter(|t| !t.is_empty() && !t.contains('/'))
                    .ok_or_else(|| invalid("shares[].tag is required"))?;
                Ok((
                    tag.to_owned(),
                    path,
                    s["readOnly"].as_bool().unwrap_or(false),
                ))
            })
            .collect::<Result<_>>()?,
        _ => return Err(invalid("shares must be an array")),
    };
    Ok(MachineSpec {
        name,
        from,
        user: text("user")?.unwrap_or_else(|| DEFAULT_LOGIN.0.to_owned()),
        cpus: number("cpus", 1..=128)?,
        memory_mib: number("memoryMiB", 256..=1 << 20)?,
        disk_gib: number("diskGiB", 4..=4096)?,
        shares,
        ports: match &args["ports"] {
            Value::Null => Vec::new(),
            ports => machines::parse_ports(ports)?,
        },
    })
}

/// The daemon VM configuration of a macOS machine in `dir`.
fn machine_vm(
    name: &str,
    dir: &Path,
    cpus: u64,
    memory_mib: u64,
    shares: &[(String, PathBuf, bool)],
) -> Value {
    json!({
        "backend": "apple-virtualization",
        "id": name,
        "guest": "macos",
        "cpus": cpus,
        "memory_mib": memory_mib,
        "disk": dir.join("disk.img"),
        "machine_identity_dir": dir.join("machine"),
        "mac_address": random_mac(),
        "screen_sharing_login": dir.join("login"),
        "width": 1920,
        "height": 1080,
        "audio": true,
        "shares": shares.iter().map(|(tag, path, read_only)| json!({"tag":tag,"path":path,"read_only":read_only})).collect::<Vec<_>>(),
    })
}

/// `machine.create` with `from`: a persistent macOS machine from a Tart
/// image (pulled when it is not in the store), set up as a container's Guest
/// is: an APFS clone of the image disk, grown to `diskGiB`, the image's
/// identity and login, and a first boot that its first command
/// (`machine.exec`, `files.copy`) finishes: the SSH key, the hostname and
/// disk, then the Accessibility and Automation grant.
pub fn create_machine(ctx: &Ctx, args: &Value, io: &StreamIo) -> Result<Value> {
    let spec = machine_spec(args)?;
    let dir = machines::dir(&spec.name)?;
    if dir.exists() || machines::vm_state(ctx, &spec.name) != "missing" {
        return Err(refuse(
            ErrorCode::State,
            format!("machine {} already exists", spec.name),
        ));
    }
    let store = Store::open(&home::images_dir()?)?;
    let image = super::with_progress(io, || container::ensure_image(&store, &spec.from, false))?;
    if image.config.os != "darwin" {
        return Err(invalid(format!(
            "{} is not a macOS image; Linux machines are created from a disk",
            spec.from
        )));
    }
    let source = store.macos_dir(&image)?;
    let config: Value = serde_json::from_slice(&fs::read(source.join("vm.json"))?)?;
    let min_cpus = config["cpuCountMin"].as_u64().unwrap_or(2);
    let min_memory = config["memorySizeMin"].as_u64().unwrap_or(4 << 30) >> 20;
    let cpus = spec
        .cpus
        .unwrap_or(config["cpuCount"].as_u64().unwrap_or(4));
    let memory_mib = spec
        .memory_mib
        .unwrap_or(config["memorySize"].as_u64().unwrap_or(8 << 30) >> 20);
    if cpus < min_cpus || memory_mib < min_memory {
        return Err(invalid(format!(
            "{} needs at least {min_cpus} CPUs and {min_memory} MiB of memory",
            spec.from
        )));
    }
    let have = fs::metadata(source.join("disk.img"))?.len();
    let want = spec.disk_gib.map(|gib| gib << 30);
    if want.is_some_and(|want| want < have) {
        return Err(invalid(format!(
            "diskGiB {} is smaller than the image's {} GiB",
            spec.disk_gib.unwrap_or_default(),
            have.div_ceil(1 << 30)
        )));
    }
    let grown = want.is_some_and(|want| want > have);
    let runtime = home::Runtime::load()?;
    let setup = first_boot(&spec.name, grown, &[], None, &runtime)?;
    home::private_dir(&dir)?;
    let result = (|| -> Result<Value> {
        io.progress("Cloning the image disk")?;
        clone_file(&source.join("disk.img"), &dir.join("disk.img"))?;
        if let Some(want) = want.filter(|_| grown) {
            io.progress("Growing the disk")?;
            super::gpt::grow(&dir.join("disk.img"), want)?;
        }
        copy_identity(
            &source,
            "nvram.bin",
            &home::private_dir(&dir.join("machine"))?,
        )?;
        write_login(&dir, &spec.user, &image_password())?;
        fs::write(dir.join("setup"), &setup)?;
        fs::write(dir.join("grant"), "")?;
        io.progress("Registering the machine")?;
        ctx.vm(
            "create",
            machine_vm(&spec.name, &dir, cpus, memory_mib, &spec.shares),
        )?;
        let machine = Machine {
            name: spec.name.clone(),
            id: random_hex(6),
            backend: "apple-virtualization".into(),
            os: "macos".into(),
            iso: None,
            disk_gib: want.unwrap_or(have).max(have).div_ceil(1 << 30),
            created_at: super::util::now(),
            icon: None,
            disk_source: None,
            image: Some(image.reference.clone()),
            drivers_iso: None,
            digest: None,
            ports: machines::record_ports(&spec.ports),
            ssh_port: None,
        };
        machines::save(&machine)?;
        Ok(machines::view(ctx, &machine))
    })();
    if result.is_err() {
        if machines::vm_state(ctx, &spec.name) != "missing" {
            let _ = ctx.vm("delete", json!({"id":spec.name,"confirm":spec.name}));
        }
        machines::cleanup_files(&dir);
    }
    result
}

/// A cloned macOS machine's files beyond its disk, in `to`: the worker
/// identity (kept, as Tart's clone keeps it; the clone has its own MAC
/// address), the login, a first-boot grant still due, and a first-boot
/// script that names the Guest after the clone.
pub fn fresh_identity(from: &Path, to: &Path, config: &mut Value) -> Result<()> {
    clone_identity(from, to, config, &home::Runtime::load()?)
}

fn clone_identity(
    from: &Path,
    to: &Path,
    config: &mut Value,
    runtime: &home::Runtime,
) -> Result<()> {
    let identity = home::private_dir(&to.join("machine"))?;
    copy_identity(&from.join("machine"), "auxiliary-storage.bin", &identity)?;
    let login = fs::read_to_string(from.join("login"))?;
    let (user, password) = login.split_once('\n').context("invalid login file")?;
    write_login(to, user, password.trim_end_matches('\n'))?;
    if from.join("grant").exists() {
        fs::write(to.join("grant"), "")?;
    }
    let name = to
        .file_name()
        .and_then(|n| n.to_str())
        .context("machine directory without a name")?;
    let pending = fs::read_to_string(from.join("setup")).unwrap_or_default();
    let rename = first_boot(name, false, &[], None, runtime)?;
    fs::write(to.join("setup"), pending + &rename)?;
    config["machine_identity_dir"] = json!(identity);
    config["screen_sharing_login"] = json!(to.join("login"));
    Ok(())
}

/// A stopped macOS machine's disk grown to `gib`: the Recovery partition
/// moves to the new end, and the next first-boot step grows APFS into it.
pub fn grow_machine_disk(dir: &Path, gib: u64) -> Result<()> {
    super::gpt::grow(&dir.join("disk.img"), gib << 30)?;
    let pending = fs::read_to_string(dir.join("setup")).unwrap_or_else(|_| "set -e\n".into());
    fs::write(dir.join("setup"), format!("{pending}{GROW_APFS}\n"))?;
    Ok(())
}

/// `machine.exec` in a macOS machine, over SSH as its login.
pub fn exec_machine(
    ctx: &Ctx,
    machine: &Machine,
    argv: &[String],
    env: &[String],
    args: &Value,
    stdin: bool,
    io: &StreamIo,
) -> Result<i32> {
    let status = ctx.vm("status", json!({"id":machine.name}))?;
    let mut guest = MachineGuest::new(machine, &status["config"])?;
    guest.env = env.to_vec();
    guest.workdir = args["cwd"].as_str().unwrap_or_default().to_owned();
    let tty = args["tty"].as_bool().unwrap_or(false);
    let command = super::with_progress(io, || -> Result<Command> {
        if let Some(user) = args["user"].as_str() {
            let (login, _) = login(&guest)?;
            if user != login {
                return Err(refuse(
                    ErrorCode::Unsupported,
                    format!("macOS commands run as the machine's login, {login}"),
                ));
            }
        }
        exec_command(&guest, argv, tty)
    })?;
    super::pump::run(command, stdin, io)
}

/// `files.copy` for a macOS machine, over scp (directories recursively).
pub fn copy_machine(
    ctx: &Ctx,
    machine: &Machine,
    inward: bool,
    host: &Path,
    path: &str,
    io: &StreamIo,
) -> Result<()> {
    let status = ctx.vm("status", json!({"id":machine.name}))?;
    let guest = MachineGuest::new(machine, &status["config"])?;
    let mut command = super::with_progress(io, || scp_command(&guest, inward, host, path))?;
    io.progress("Copying over SSH")?;
    let output = command.stdin(Stdio::null()).output()?;
    if !output.status.success() {
        bail!(
            "scp failed: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )
    }
    Ok(())
}

