//! macOS containers and machines: Tart-format images run as Apple
//! Virtualization macOS VMs. A machine (`machine.create {from}`) has the same
//! files under `<home>/machines/NAME`; [`Guest`] is what the SSH helpers need
//! of either.
//!
//! ```text
//! <container>/disk.img                       APFS clone of the image disk
//! <container>/machine/hardware-model.bin     copied from the image
//! <container>/machine/auxiliary-storage.bin  APFS clone of the image NVRAM
//! <container>/machine/machine-id.bin         copied from the image (as Tart does: a new
//!                                            identity makes the Guest run Setup Assistant
//!                                            over every window), else generated by the worker
//! <container>/login                          "user\npassword" of the image login (0600)
//! <container>/known_hosts                    Guest host key, trusted on first use
//! <container>/setup                          first-boot root script (hostname, disk, DNS, MTU)
//! <container>/grant                          marker: the first-boot TCC grant is still due
//! ```
//!
//! The Guest address is the vmnet DHCP lease for the container's fixed MAC.
//! Commands and copies use the system ssh/scp with a per-home key, which the
//! first command installs with the image login (Tart images: admin/admin).
//! The Guest gets Apple's paravirtualized Metal GPU. There is no entrypoint:
//! `run IMAGE COMMAND` runs the command over SSH once the Guest is up (in the
//! foreground, or with `-d` in the background with its output in
//! `~/.veynodevm/main.log`, which `logs` reads), and `run -it IMAGE` opens a
//! login shell. The first boot finishes inside `run` (also with `-d`): after
//! the key and the setup script, `macos_grant` gives SSH sessions
//! Accessibility and Automation of System Events through the Guest's screen.
